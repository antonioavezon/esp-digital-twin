def catalog(lang: str) -> dict:
    return STRINGS["en"] if lang == "en" else STRINGS["es"]


def text_for(request, key: str) -> str:
    return catalog(language_of(request))[key]


def localize_esp(esp: dict | None, lang: str) -> dict | None:
    if not esp or lang != "en":
        return esp
    for component in esp.get("components", []):
        overlay = COMPONENTS_EN.get(component.get("id"))
        if not overlay:
            continue
        name, location, description, function, inlet, outlet, relation = overlay
        component["name"] = name
        component["location_label"] = location
        component["description"] = description
        component["function"] = function
        component["input"] = inlet
        component["output"] = outlet
        component["relation"] = relation
    flows = esp.get("flows") or {}
    for key in ("energy", "fluid"):
        flow = flows.get(key)
        pack = FLOW_EN.get(key)
        if not flow or not pack:
            continue
        flow["name"], flow["description"] = pack
        for step in flow.get("steps", []):
            label = STEP_EN.get(step.get("component_id"))
            if label:
                step["label"] = label
    return esp
